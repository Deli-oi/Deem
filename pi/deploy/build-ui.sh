#!/usr/bin/env bash
#
# Build the Deem health UI (demo/) for the Pi touchscreen, in LIVE mode.
#
# Vite bakes VITE_* variables in at build time, so we write them to
# demo/.env.local (git-ignored) before building. The UI then talks to the real
# ESP32 over the Pi's Mosquitto WebSocket listener instead of the fixture mock.
#
# Override the broker URL / pot id via the environment if your setup differs:
#   VITE_MQTT_URL=ws://deem-pi.local:9001 VITE_DEVICE_ID=esp32-pot-02 ./build-ui.sh
set -euo pipefail

DEMO_DIR="$(cd "$(dirname "$0")/../../demo" && pwd)"
cd "${DEMO_DIR}"

VITE_MQTT_URL="${VITE_MQTT_URL:-ws://localhost:9001}"
VITE_DEVICE_ID="${VITE_DEVICE_ID:-esp32-pot-01}"
# The Pi serves static files only, so voice (Fish Audio speech-to-text) goes to the hosted Deem server,
# which holds the API key. The key is never on the Pi.
VITE_API_BASE="${VITE_API_BASE:-https://deem-production.up.railway.app}"
VITE_TRANSCRIBE_URL="${VITE_TRANSCRIBE_URL:-${VITE_API_BASE}/api/transcribe}"

echo "building Deem UI (live mode)"
echo "  broker:  ${VITE_MQTT_URL}"
echo "  device:  ${VITE_DEVICE_ID}"
echo "  voice:   ${VITE_TRANSCRIBE_URL}"
echo "  plants + answers (Gemini): ${VITE_API_BASE}"

# .env.local is git-ignored (keeps the device-specific URL out of the repo) and
# is loaded by Vite for the production build.
cat > .env.local <<EOF
# Generated by pi/deploy/build-ui.sh — do not commit.
VITE_BACKEND=mqtt
VITE_MQTT_URL=${VITE_MQTT_URL}
VITE_DEVICE_ID=${VITE_DEVICE_ID}
VITE_API_BASE=${VITE_API_BASE}
VITE_TRANSCRIBE_URL=${VITE_TRANSCRIBE_URL}
EOF

# npm ci for a clean, reproducible install when a lockfile is present.
if [ -f package-lock.json ]; then
  npm ci
else
  npm install
fi

npm run build
echo "done. Serve it with deem-ui.service (or: npm start)."
