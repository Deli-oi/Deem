"""Writes docs/plant_thresholds.md: every plant's out-of-range values, straight from seed_all.json.

    python data/plants/thresholds_report.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
plants = json.loads((root / "demo/public/plants/seed_all.json").read_text(encoding="utf-8"))

MEASURED = [  # readings our sensors report that have ranges in the plant data
    ("soil_moisture", "Soil moisture (%)", "Soil too dry", "Soil too wet"),
    ("temp_c", "Temperature (°C)", "Too cold", "Too hot"),
    ("rh_pct", "Air humidity (%)", "Air too dry", "Air too humid"),
]
NO_SENSOR = [("soil_ec", "Soil nutrients EC (µS/cm)"), ("light_lux", "Light (lux)"), ("light_mmol", "Light (mmol)")]


def rng(p, key):
    r = p["thresholds"].get(key)
    return f"{r['min']} to {r['max']}" if r and r["min"] is not None and r["max"] is not None else "missing"


def fix_for(p, key, op):
    for s in p["solutions"]:
        t = s.get("trigger")
        if t and t["metric"] == key and t["op"] == op:
            return s["problem"]
    return "missing"


lines = [
    "# Plant healthy ranges and out-of-range values",
    "",
    "Generated by `data/plants/thresholds_report.py` from `demo/public/plants/seed_all.json`. Do not edit by hand.",
    "",
    "A reading **outside** a plant's healthy range raises an alert (sound + on-screen message). "
    "The ranges come from MiFloraDB (Xiaomi Flower Care), i.e. the extremes the plant tolerates, not an ideal range, "
    "so an alert means it needs fixing now.",
    "",
    "## Readings we measure (alerts work today)",
    "",
    "| Plant | " + " | ".join(m[1] for m in MEASURED) + " |",
    "|---|" + "---|" * len(MEASURED),
]
for p in plants:
    lines.append(f"| {p['common_names'][0]} | " + " | ".join(rng(p, m[0]) for m in MEASURED) + " |")
lines += ["", "Alert text: " + "; ".join(f"{m[1].split(' (')[0]}: **{m[2]}** below, **{m[3]}** above" for m in MEASURED) + ".", "",
          "Every plant also has a stored fix for each of these six cases (the answer the assistant gives), "
          "and each fix triggers at exactly that plant's own bound. This is enforced by `demo/server/plants.test.mjs`.", "",
          "## Ranges with no sensor yet (stored, never alert)", "",
          "| Plant | " + " | ".join(n[1] for n in NO_SENSOR) + " |", "|---|" + "---|" * len(NO_SENSOR)]
for p in plants:
    lines.append(f"| {p['common_names'][0]} | " + " | ".join(rng(p, n[0]) for n in NO_SENSOR) + " |")
lines += ["", "These start alerting automatically as soon as a sensor reports `soil_ec` or `light_lux` in telemetry.", "",
          "## Measured, but no ranges", "",
          "- `co2_ppm`, `pm1_0`, `pm2_5`, `pm4_0`, `pm10_0` (SEN63C air quality): not in the plant data and not plant-specific. No alerts yet.",
          "- `soil_temp_c` (Stemma soil sensor): no ranges. No alerts yet.", ""]
(root / "docs/plant_thresholds.md").write_text("\n".join(lines), encoding="utf-8")
print("wrote docs/plant_thresholds.md")
